'use strict';
// Extracts the farm-publishing slice of shell/renderer/app.js into a standalone classic script for
// the chat harness (plan §2.2.1). The harness must never carry a COPY of publishFarm: if app.js
// changes shape, this extraction fails loudly instead of testing a stale bridge.
//
//   const { buildWrapper, extract, write, ANCHORS } = require('./extract-app-bridge.js');
//   const src = buildWrapper(fs.readFileSync(appJs, 'utf8'));   // the wrapper source
//   write(path.join(__dirname, 'generated', 'app-bridge.js'));  // read app.js + write the file
//
// The wrapper exposes `window.__appBridge = { set(farmState, sidecarState), publishFarm }`;
// harness-bridge.js feeds it main-shaped farm objects and the REAL publishFarm builds
// `window.__lolFarm`. `shell/test/chat/unit/bridge.test.mjs` runs the same wrapper in node:vm.

const fs = require('fs');
const path = require('path');

const ANCHORS = {
    /** slice 1: the farm helpers (farmEndpoint + activeFarm) */
    helpersStart: 'const farmEndpoint = ',
    helpersEnd: '// ---- topbar connection pill',
    /** slice 2: publishFarm itself */
    publishStart: 'function publishFarm() {',
    publishEnd: '// OWUI is the primary surface',
};

const APP_JS = path.join(__dirname, '..', '..', 'renderer', 'app.js');

/**
 * @param {string} src
 * @param {string} start
 * @param {string} end
 * @param {string} what
 * @returns {string}
 */
function sliceBetween(src, start, end, what) {
    const a = src.indexOf(start);
    if (a < 0) throw new Error(`extract-app-bridge: anchor not found in app.js for ${what}: ${JSON.stringify(start)}`);
    const b = src.indexOf(end, a);
    if (b < 0) throw new Error(`extract-app-bridge: end anchor not found in app.js for ${what}: ${JSON.stringify(end)}`);
    const text = src.slice(a, b).trimEnd();
    if (!text) throw new Error(`extract-app-bridge: empty slice for ${what}`);
    return text;
}

/**
 * Build the standalone wrapper source from app.js text.
 * @param {string} appJsSource
 * @returns {string}
 */
function buildWrapper(appJsSource) {
    if (typeof appJsSource !== 'string' || !appJsSource.trim()) throw new Error('extract-app-bridge: app.js source is empty');
    const helpers = sliceBetween(appJsSource, ANCHORS.helpersStart, ANCHORS.helpersEnd, 'farmEndpoint/activeFarm');
    const publish = sliceBetween(appJsSource, ANCHORS.publishStart, ANCHORS.publishEnd, 'publishFarm');
    if (!/function\s+activeFarm|activeFarm\s*=/.test(helpers)) {
        throw new Error('extract-app-bridge: the helpers slice does not define activeFarm — app.js changed shape');
    }
    if (!/window\.__lolFarm/.test(publish)) {
        throw new Error('extract-app-bridge: the publishFarm slice does not assign window.__lolFarm — app.js changed shape');
    }
    return `// GENERATED by shell/test/chat-harness/extract-app-bridge.js — do not edit, do not commit.
// Slices of shell/renderer/app.js, verbatim, so the harness exercises the REAL publishFarm.
(function () {
  let farmState = { farms: [] }, sidecarState = null;
  const NO_OWUI = false; function renderSidecar() {}
${helpers.split('\n').map((l) => (l ? '  ' + l : l)).join('\n')}
${publish.split('\n').map((l) => (l ? '  ' + l : l)).join('\n')}
  window.__appBridge = { set(fs, ss) { farmState = fs; sidecarState = ss; }, publishFarm };
})();
`;
}

/** Read the repo's app.js and build the wrapper. @returns {string} */
function extract(appJsPath) {
    const p = appJsPath || APP_JS;
    let src;
    try {
        src = fs.readFileSync(p, 'utf8');
    } catch (e) {
        throw new Error(`extract-app-bridge: cannot read ${p}: ${e && e.message}`);
    }
    return buildWrapper(src);
}

/** Write generated/app-bridge.js (creating the folder). @returns {string} the path written */
function write(dest, appJsPath) {
    const out = dest || path.join(__dirname, 'generated', 'app-bridge.js');
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, extract(appJsPath));
    return out;
}

module.exports = { ANCHORS, APP_JS, buildWrapper, extract, write, sliceBetween };

if (require.main === module) {
    const out = write();
    console.log(`[extract-app-bridge] wrote ${out}`);
}
